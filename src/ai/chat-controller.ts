/**
 * Chat state machine with per-document session isolation.
 *
 * The rule that keeps documents from bleeding into each other: every request
 * carries a `requestId`, and events for an id that is no longer current are
 * **dropped**, not appended. Switching documents or asking a new question
 * retires the previous id, so a late delta from a cancelled request can never
 * appear in the new document's transcript.
 *
 * Exactly one terminal event per request is enforced here as well: once a turn
 * reaches completed/cancelled/error it stops accepting deltas, so the UI can
 * never be stuck showing "generating".
 */

import type {
  ChatMessage,
  ChatPhase,
  ChatTurn,
  ContentPart,
  ContextMode,
  ContextStats,
  ImageAttachment,
} from "./types";
import { toStoredChat, type StoredChat } from "./chat-history.js";

export interface ChatControllerDeps {
  /** Send a request and feed events back through `onEvent`. */
  startChat: (
    requestId: string,
    profileId: string,
    messages: ChatMessage[],
    onEvent: (ev: import("./types").AiStreamEvent) => void,
    temperature?: number,
    sessionId?: string
  ) => Promise<void>;
  cancelChat: (requestId: string) => Promise<boolean>;
  onChange: () => void;
  newId: () => string;
  now?: () => number;
}

/** One document's transcript. Discarded when the document closes. */
interface Session {
  documentId: string;
  /**
   * Stable id for this conversation, sent as `x-opencode-session` for
   * providers that ask for it. Regenerated by newConversation() so a fresh
   * conversation gets fresh routing/caching, which is what the header is for.
   */
  conversationId: string;
  turns: ChatTurn[];
  /** The request that is allowed to append to this session. */
  activeRequestId: string | null;
  contextMode: ContextMode;
  profileId: string | null;
}

const TERMINAL: ChatPhase[] = ["completed", "cancelled", "error"];

function isTerminal(p: ChatPhase): boolean {
  return TERMINAL.includes(p);
}

export class ChatController {
  private sessions = new Map<string, Session>();
  private currentDocumentId: string | null = null;
  /** Incremented per request so a stale channel callback is ignored. */
  private generation = 0;

  constructor(private deps: ChatControllerDeps) {}

  // ------------------------------------------------------------- sessions

  /**
   * Load a persisted conversation into the current session.
   *
   * Called once, when a document is opened. Deliberately replaces rather than
   * appends: the file is the whole history for that document, and appending on a
   * re-open after a failed save would duplicate every turn.
   *
   * Only meaningful before the user has asked anything — hence the guard. A
   * restore that lands mid-conversation would put yesterday's turns in front of
   * today's answer.
   */
  restoreTurns(turns: ChatTurn[]): void {
    const s = this.session();
    if (!s) return;
    if (s.turns.length) return;
    s.turns.push(...turns);
    this.deps.onChange();
  }

  /**
   * The current session in the shape the store persists.
   *
   * A snapshot, not a reference: saving must not be able to mutate the live
   * session, and the caller writes it asynchronously.
   */
  snapshotForStorage(documentTitle?: string): StoredChat {
    return toStoredChat({
      documentTitle,
      turns: this.session()?.turns.slice() ?? [],
    });
  }

  openDocument(documentId: string | null): void {
    if (documentId === this.currentDocumentId) return;

    // Retire the outgoing document's in-flight request BEFORE switching the
    // pointer. Three things have to happen together, and the third is the one
    // that is easy to miss:
    //   1. ask the backend to stop it;
    //   2. clear its activeRequestId on the old session;
    //   3. bump the generation so already-queued deltas are dropped.
    // Without (3) a delta that was already in the event queue lands in the
    // *original* document's transcript after the user has left it, and silently
    // appears if they later switch back. Covered by
    // "a late delta cannot leak into the document the user switched to".
    const old = this.session();
    if (old?.activeRequestId) {
      const reqId = old.activeRequestId;
      const turn = old.turns.find((t) => t.id === reqId);
      if (turn && !isTerminal(turn.phase)) {
        turn.phase = "cancelled";
      }
      old.activeRequestId = null;
      void this.deps.cancelChat(reqId).catch(() => false);
    }
    this.generation++;

    this.currentDocumentId = documentId;
    if (documentId && !this.sessions.has(documentId)) {
      this.sessions.set(documentId, {
        documentId,
        conversationId: this.deps.newId(),
        turns: [],
        activeRequestId: null,
        contextMode: "selection",
        profileId: null,
      });
    }
    this.deps.onChange();
  }

  /** Drop a document's transcript (closing the file). */
  closeDocument(documentId: string): void {
    this.sessions.delete(documentId);
    if (this.currentDocumentId === documentId) {
      this.currentDocumentId = null;
    }
    this.deps.onChange();
  }

  private session(): Session | null {
    if (!this.currentDocumentId) return null;
    return this.sessions.get(this.currentDocumentId) ?? null;
  }

  turns(): ChatTurn[] {
    return this.session()?.turns.slice() ?? [];
  }

  contextMode(): ContextMode {
    return this.session()?.contextMode ?? "selection";
  }

  setContextMode(mode: ContextMode): void {
    const s = this.session();
    if (!s) return;
    s.contextMode = mode;
    this.deps.onChange();
  }

  profileId(): string | null {
    return this.session()?.profileId ?? null;
  }

  setProfileId(id: string | null): void {
    const s = this.session();
    if (!s) return;
    s.profileId = id;
    this.deps.onChange();
  }

  isBusy(): boolean {
    const s = this.session();
    if (!s?.activeRequestId) return false;
    const t = s.turns.find((x) => x.id === s.activeRequestId);
    return !!t && !isTerminal(t.phase);
  }

  // --------------------------------------------------------------- sending

  /**
   * Append the user turn and start streaming the assistant turn.
   * Returns the assistant turn id, or null when there is nothing to send.
   */
  async send(opts: {
    question: string;
    messages: ChatMessage[];
    contextLabel: string;
    stats: ContextStats;
    /** Screenshots sent with this question, kept for the transcript. */
    attachments?: ImageAttachment[];
    /**
     * The active provider's per-image token charge, when it publishes one.
     *
     * Passed in rather than looked up here: the controller has no business
     * reading provider settings, and the value is only used to render the
     * transcript line.
     */
    imageTokens?: number;
  }): Promise<string | null> {
    const s = this.session();
    if (!s) return null;
    if (this.isBusy()) return null;
    const profileId = s.profileId;
    if (!profileId) return null;

    const now = this.deps.now ?? Date.now;
    const attachments = opts.attachments ?? [];
    const userTurn: ChatTurn = {
      id: this.deps.newId(),
      role: "user",
      content: opts.question,
      phase: "completed",
      contextLabel: `${opts.contextLabel} · ${describeStats(opts.stats, opts.imageTokens)}`,
      // Shown in the transcript because a question whose only subject is a
      // figure is unreadable later without the figure.
      attachments: attachments.length ? attachments : undefined,
      createdAt: now(),
    };
    const assistantTurn: ChatTurn = {
      id: this.deps.newId(),
      role: "assistant",
      content: "",
      phase: "preparing",
      contextLabel: opts.contextLabel,
      createdAt: now(),
    };
    s.turns.push(userTurn, assistantTurn);

    const requestId = assistantTurn.id;
    s.activeRequestId = requestId;
    const myGeneration = ++this.generation;
    // Remember which session this request belongs to: the callback must not
    // write into a different document's transcript.
    const ownerDocument = s.documentId;
    this.deps.onChange();

    const accept = (): Session | null => {
      if (myGeneration !== this.generation) return null;
      const target = this.sessions.get(ownerDocument);
      if (!target || target.activeRequestId !== requestId) return null;
      const turn = target.turns.find((t) => t.id === requestId);
      if (!turn || isTerminal(turn.phase)) return null;
      return target;
    };

    try {
      await this.deps.startChat(
        requestId,
        profileId,
        opts.messages,
        (ev) => {
          const target = accept();
          if (!target) return; // stale — dropped on purpose
          const turn = target.turns.find((t) => t.id === requestId)!;
          switch (ev.type) {
            case "started":
              turn.phase = "streaming";
              break;
            case "delta":
              turn.phase = "streaming";
              turn.content += ev.text;
              break;
            case "completed":
              turn.phase = "completed";
              target.activeRequestId = null;
              break;
            case "cancelled":
              turn.phase = "cancelled";
              target.activeRequestId = null;
              break;
            case "error":
              turn.phase = "error";
              turn.errorCode = ev.code;
              turn.errorMessage = ev.safe_message;
              target.activeRequestId = null;
              break;
          }
          this.deps.onChange();
        },
        undefined,
        // Stable for the whole conversation; regenerated by newConversation().
        s.conversationId
      );
    } catch (e) {
      // The IPC call itself failed (e.g. no key stored). Surface it on the
      // turn rather than throwing into the caller's click handler.
      const target = accept();
      if (target) {
        const turn = target.turns.find((t) => t.id === requestId)!;
        turn.phase = "error";
        turn.errorMessage = String(e);
        turn.errorCode = extractCode(e);
        target.activeRequestId = null;
        this.deps.onChange();
      }
    }

    return requestId;
  }

  /** Ask the running request to stop. */
  async cancelActive(): Promise<void> {
    const s = this.session();
    const id = s?.activeRequestId;
    if (!s || !id) return;
    const turn = s.turns.find((t) => t.id === id);
    if (turn && !isTerminal(turn.phase)) {
      turn.phase = "cancelling";
      this.deps.onChange();
    }
    try {
      await this.deps.cancelChat(id);
    } catch {
      /* the stream will end on its own */
    }
    // The backend will send `cancelled`; if it does not (already finished),
    // settle the turn so the UI is not stuck.
    const after = s.turns.find((t) => t.id === id);
    if (after && !isTerminal(after.phase) && after.phase === "cancelling") {
      after.phase = "cancelled";
      s.activeRequestId = null;
      this.deps.onChange();
    }
  }

  /** Clear the transcript for the current document (keep the context mode). */
  newConversation(): void {
    const s = this.session();
    if (!s) return;
    void this.cancelActive();
    s.turns = [];
    s.activeRequestId = null;
    s.conversationId = this.deps.newId();
    this.generation++;
    this.deps.onChange();
  }

  /**
   * Recent (user, assistant) pairs to send as history.
   *
   * Bounded on purpose: re-sending the whole transcript every turn makes cost
   * grow quadratically. Only *completed* assistant turns qualify — a cancelled
   * or failed one carries no usable answer.
   */
  history(limit = 6): ChatMessage[] {
    return this.recentWindow(limit).messages;
  }

  /**
   * Page numbers whose images are still inside the history window.
   *
   * Exists because of a cost trap in whole-document image mode. The API is
   * stateless, so a follow-up question has to carry the document again — and the
   * history already does: a past question turn is rebuilt with its images intact
   * (see `questionWithImages`). Re-rendering the pages on top of that sends the
   * same 7 pages twice, doubling the most expensive part of the request for
   * nothing.
   *
   * So the builder asks which pages the model can already see, and skips them.
   * The window is the same one `history()` uses, by construction — they share
   * `recentWindow` — because a page trimmed out of the history is a page the
   * model can no longer see, and skipping its render would lose the document
   * entirely.
   */
  pagesInHistory(limit = 6): number[] {
    return [...this.recentWindow(limit).pages].sort((a, b) => a - b);
  }

  /**
   * The history window as whole (question, answer) pairs, plus the document
   * pages their images cover.
   *
   * One walk, two consumers, deliberately: `history()` and `pagesInHistory()`
   * must agree exactly. If they used separate walks with separate limits, the
   * builder could skip a page the controller had already trimmed out, and the
   * model would be asked about a page it cannot see.
   *
   * Pairs are kept whole rather than slicing a flat list, so a question is never
   * separated from its answer. For the default even limit this is identical to
   * the old flat slice; for an odd one it is strictly better.
   */
  private recentWindow(limit: number): { messages: ChatMessage[]; pages: Set<number> } {
    const s = this.session();
    if (!s) return { messages: [], pages: new Set() };

    const groups: { messages: ChatMessage[]; pages: Set<number> }[] = [];
    for (let i = 0; i < s.turns.length; i++) {
      const t = s.turns[i];
      if (t.role !== "assistant" || t.phase !== "completed" || !t.content.trim()) continue;
      const prev = s.turns[i - 1];
      if (prev?.role !== "user") continue;

      const attachments = prev.attachments ?? [];
      const pages = new Set<number>();
      for (const a of attachments) {
        if (a.source === "page" && typeof a.page === "number") pages.add(a.page);
      }
      groups.push({
        messages: [
          {
            role: "user",
            content: attachments.length
              ? questionWithImages(prev.content, attachments)
              : prev.content,
          },
          { role: "assistant", content: t.content },
        ],
        pages,
      });
    }

    // Walk backwards, keeping whole pairs, until the message budget is spent.
    const messages: ChatMessage[] = [];
    const pages = new Set<number>();
    for (let i = groups.length - 1; i >= 0 && messages.length < limit; i--) {
      const g = groups[i];
      messages.unshift(...g.messages);
      for (const p of g.pages) pages.add(p);
    }
    return { messages, pages };
  }
}

/**
 * Rebuild a past question's content, images included.
 *
 * The transcript shows the question text and the thumbnails separately, but the
 * wire format needs them together. Dropping the images here would leave the
 * model answering follow-ups about a figure it can no longer see — and the user
 * with no way to tell why the answers stopped making sense.
 */
function questionWithImages(
  question: string,
  attachments: ImageAttachment[]
): ChatMessage["content"] {
  const parts: ContentPart[] = [{ type: "text", text: question }];
  for (const a of attachments) {
    parts.push({ type: "image_url", image_url: { url: a.url } });
  }
  return parts;
}

/**
 * Human-readable breakdown of what a request carried.
 *
 * The image part is the reason this is not a one-liner. A page image costs the
 * provider's per-image charge, which is not derivable from the base64 length —
 * the same 200 KB JPEG can cost 384 tokens or 1700 depending on whether the
 * provider uses a flat cap or tiles by resolution.
 *
 * So:
 *  - provider publishes a flat cap  -> show the arithmetic ("7 张图片 ≈ 2688 token")
 *  - provider does not              -> show the count and say the cost is theirs
 *  - never                           -> a made-up number
 *
 * The old version showed only `chars / tokens`, which read "9 字 / 约 3 tokens"
 * next to seven images and a request that actually cost ~3000. A number that
 * far off is worse than no number: it makes the expensive path look free.
 */
function describeStats(s: ContextStats, imageTokens?: number): string {
  const base = `${s.chars} 字 / 约 ${s.approx_tokens} tokens`;
  const images = describeImages(s.images, imageTokens);
  if (!s.chars && !s.images) return "无文献内容";
  // Say so when the document did not fit. Without this the transcript claims a
  // full-paper question was answered from the full paper.
  if (s.truncated && s.pages_sent.length && s.pages_total) {
    const last = s.pages_sent[s.pages_sent.length - 1];
    return `${base}${images} · 仅第 ${s.pages_sent[0]}–${last} 页 / 共 ${s.pages_total} 页`;
  }
  return base + images;
}

/**
 * The image part of the breakdown.
 *
 * When the per-image charge is known, the images are folded into a total and
 * shown as their own line — because they dominate the request and burying them
 * in a single figure hides the thing the user is paying for. When it is not
 * known, the count is shown with a plain statement that the cost is the
 * provider's, which is honest and still tells the user seven images went out.
 */
function describeImages(count: number, imageTokens?: number): string {
  if (!count) return "";
  if (imageTokens === undefined || !Number.isFinite(imageTokens) || imageTokens <= 0) {
    return ` · ${count} 张图片（成本由提供商按图计费，本地无法估算）`;
  }
  const total = count * imageTokens;
  return ` · ${count} 张图片 ≈ ${total} token（按每张 ${imageTokens}）`;
}

/** Tauri rejects with a plain string or `{code,message}`; normalise both. */
function extractCode(e: unknown): string | undefined {
  if (typeof e === "object" && e && "code" in e) {
    return String((e as { code: unknown }).code);
  }
  const m = /\[([a-z_]+)\]/.exec(String(e));
  return m?.[1];
}
